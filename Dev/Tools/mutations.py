def sciezka(p):
    return p.replace('{SRC}', SRC).replace('{WALIDATOR}', WALIDATOR).replace('{DEFS}', DEFS)


def run_validator():
    """Zwraca (ok, bledow, linie_bledow, nie_kompiluje_sie).

    Brak podsumowania ma dwie rozne przyczyny i nie wolno ich mieszac: blad KOMPILACJI oznacza,
    ze mutacja w ogole nie weszla do testowanego kodu (niczego nie dowodzi - NIEWAZNA), a awaria
    w czasie dzialania (wyjatek) jest wykryciem - walidator padl na zmienionym zachowaniu.
    Kod bledu kompilatora (CSxxxx/MSBxxxx) nie jest tlumaczony, slowo przed nim bywa."""
    p = subprocess.run(['dotnet', 'run', '-c', 'Release'], cwd=WALIDATOR, capture_output=True, text=True,
                       encoding='utf-8', errors='replace', timeout=900)
    out = p.stdout + p.stderr
    m = re.search(r'PODSUMOWANIE: (\d+) OK, (\d+) BLEDOW', out)
    if not m:
        kompilacja = re.search(r'(error|b\u0142\u0105d)\s+(CS|MSB)\d{4}', out, re.IGNORECASE) is not None
        err = [l for l in out.splitlines() if 'error' in l or 'Exception' in l][:2]
        # Asercje, ktore padly PRZED awaria, sa czescia dowodu - bez nich plik wynikowy zanizal
        # sile wykrycia (przeglad S6: B8 i B20 mialy padniete asercje, a raport pokazywal tylko wyjatek).
        bledy = [l.strip() for l in out.splitlines() if l.strip().startswith('[BLAD]')]
        return None, None, bledy + err, kompilacja
    fails = [l.strip() for l in out.splitlines() if l.strip().startswith('[BLAD]')]
    return int(m.group(1)), int(m.group(2)), fails, False


def main():
    args = sys.argv[1:]
    tylko_sprawdz = '--sprawdz' in args
    wybrane = [a for a in args if not a.startswith('--')]
    wykryte = niewykryte = nieaktualne = niewazne = 0
    for name, path, old, new in INJ:
        if wybrane and name.split()[0] not in wybrane:
            continue
        path = sciezka(path)
        raw = io.open(path, 'rb').read()
        txt = raw.decode('utf-8')
        crlf = '\r\n' in txt
        norm = txt.replace('\r\n', '\n')
        if norm.count(old) != 1:
            nieaktualne += 1
            print('%-48s WZORZEC NIEAKTUALNY (wystapien: %d)' % (name, norm.count(old)))
            continue
        if tylko_sprawdz:
            print('%-48s wzorzec OK' % name)
            continue
        zm = norm.replace(old, new)
        if crlf:
            zm = zm.replace('\n', '\r\n')
        try:
            io.open(path, 'wb').write(zm.encode('utf-8'))
            ok, bad, fails, nie_kompiluje = run_validator()
        finally:
            io.open(path, 'wb').write(raw)
        if ok is None and nie_kompiluje:
            niewazne += 1
            print('%-48s *** NIEWAZNA: mutacja sie nie kompiluje *** %s' % (name, [f[:120] for f in fails]))
        elif ok is None:
            wykryte += 1
            print('%-48s PRZEBIEG PADL (wykryte przez awarie w czasie dzialania) %s'
                  % (name, [f[:120] for f in fails]))
        else:
            if bad > 0:
                wykryte += 1
            else:
                niewykryte += 1
            print('%-48s %s (%d bledow)' % (name, 'WYKRYTE' if bad > 0 else '*** NIEWYKRYTE ***', bad))
            for f in fails[:2]:
                print('      ' + f[:150].encode('ascii', 'replace').decode())
        sys.stdout.flush()
    print('PODSUMOWANIE MUTACJI: wykryte %d, NIEWYKRYTE %d, nieaktualne wzorce %d, NIEWAZNE %d'
          % (wykryte, niewykryte, nieaktualne, niewazne))
    if not tylko_sprawdz:
        ok, bad, _, _ = run_validator()
        print('PO PRZYWROCENIU:', ok, 'OK,', bad, 'BLEDOW')
    sys.exit(1 if (niewykryte or nieaktualne or niewazne) else 0)


if __name__ == '__main__':
    main()
